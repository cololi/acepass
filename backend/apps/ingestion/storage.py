"""Private file storage adapter.

Every stored object is addressed by an opaque key generated by the server.
User input never determines a path. The default backend is a private local
directory; an S3-compatible backend can be added behind the same interface.
"""

from __future__ import annotations

import hashlib
import os
import secrets
import shutil
from abc import ABC, abstractmethod
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO

from django.conf import settings


class StorageError(RuntimeError):
    pass


class ObjectNotFound(StorageError):
    pass


@dataclass(frozen=True)
class StoredObject:
    key: str
    size: int
    checksum: str


class PrivateStorage(ABC):
    """Interface used by the ingestion and tutoring modules."""

    name = "abstract"

    @abstractmethod
    def save(self, key_hint: str, content: bytes | BinaryIO, *, content_type: str = "") -> StoredObject: ...

    @abstractmethod
    def open(self, key: str) -> BinaryIO: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def delete(self, key: str) -> None: ...

    @abstractmethod
    def size(self, key: str) -> int: ...

    def absolute_path(self, key: str) -> Path | None:
        """Local backends may expose a path for FileResponse; others return None."""
        return None


def build_key(namespace: str, suffix: str) -> str:
    """Server-generated, non-guessable object key.

    The key never contains the original filename, so a leaked key cannot be
    enumerated and the original name cannot traverse out of the storage root.
    """
    safe_namespace = "".join(ch for ch in namespace if ch.isalnum() or ch in {"/", "-", "_"}).strip("/")
    safe_suffix = "".join(ch for ch in suffix.lower() if ch.isalnum())[:12]
    token = secrets.token_hex(16)
    return f"{safe_namespace}/{token[:2]}/{token}{'.' + safe_suffix if safe_suffix else ''}"


class LocalPrivateStorage(PrivateStorage):
    name = "local"

    def __init__(self, root: Path | str | None = None):
        self.root = Path(root or settings.PRIVATE_MEDIA_ROOT).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _resolve(self, key: str) -> Path:
        if not key or key.startswith("/") or ".." in Path(key).parts:
            raise StorageError("invalid object key")
        path = (self.root / key).resolve()
        if not str(path).startswith(str(self.root)):
            raise StorageError("object key escapes storage root")
        return path

    def save(self, key_hint: str, content: bytes | BinaryIO, *, content_type: str = "") -> StoredObject:
        path = self._resolve(key_hint)
        path.parent.mkdir(parents=True, exist_ok=True)
        digest = hashlib.sha256()
        size = 0
        tmp_path = path.with_suffix(path.suffix + ".part")
        with open(tmp_path, "wb") as handle:
            if isinstance(content, (bytes, bytearray)):
                handle.write(content)
                digest.update(content)
                size = len(content)
            else:
                while True:
                    chunk = content.read(1024 * 256)
                    if not chunk:
                        break
                    handle.write(chunk)
                    digest.update(chunk)
                    size += len(chunk)
        os.replace(tmp_path, path)
        return StoredObject(key=key_hint, size=size, checksum=digest.hexdigest())

    def open(self, key: str) -> BinaryIO:
        path = self._resolve(key)
        if not path.is_file():
            raise ObjectNotFound(key)
        return open(path, "rb")

    def exists(self, key: str) -> bool:
        try:
            return self._resolve(key).is_file()
        except StorageError:
            return False

    def delete(self, key: str) -> None:
        path = self._resolve(key)
        if path.is_file():
            path.unlink()

    def size(self, key: str) -> int:
        path = self._resolve(key)
        if not path.is_file():
            raise ObjectNotFound(key)
        return path.stat().st_size

    def absolute_path(self, key: str) -> Path | None:
        path = self._resolve(key)
        return path if path.is_file() else None


_storage: PrivateStorage | None = None


def get_storage() -> PrivateStorage:
    """Return the configured storage backend (cached per process)."""
    global _storage
    if _storage is not None:
        return _storage
    backend = getattr(settings, "STORAGE_BACKEND", "local")
    if backend == "local":
        _storage = LocalPrivateStorage()
    else:  # pragma: no cover - only reached with an explicit S3 configuration
        raise StorageError(
            f"storage backend {backend!r} is not implemented in P0; use 'local' "
            "(see docs/implementation-status.md)"
        )
    return _storage


def reset_storage_cache() -> None:
    global _storage
    _storage = None


def wipe_storage(root: Path | str | None = None) -> None:  # pragma: no cover - test helper
    target = Path(root or settings.PRIVATE_MEDIA_ROOT)
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True, exist_ok=True)

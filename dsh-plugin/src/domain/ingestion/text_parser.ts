/**
 * Parse an answer page/section into `{position: raw answer}` entries.
 *
 * Deliberately conservative: only lines that clearly start with a question number become entries,
 * everything else is reported as unparsed so the proofreader sees what the parser could not place.
 * Multi-line answers are joined until the next numbered entry.
 */
export function parseAnswerPage(text: string): AnswerPageResult {
  const entries: AnswerEntry[] = []
  const unparsed: string[] = []
  let current: AnswerEntry | null = null

  for (const rawLine of pySplitlines(text ?? '')) {
    const line = pyStrip(rawLine)
    if (!line) continue
    const header = SECTION_PATTERN.exec(line)
    if (header !== null && !Object.hasOwn(SECTION_LABELS, pyStrip(header[1]))) {
      // A heading such as 【参考答案】 introduces the section, not an answer.
      if (header[1].includes('答案') || header[1].includes('解析')) continue
    } else if (header === null && ANSWER_HEADINGS.some((marker) => pyRstripChars(line, '：: ') === pyRstripChars(marker, '：: '))) {
      continue
    }
    const match = ANSWER_ENTRY_PATTERN.exec(line)
    if (match !== null && looksLikeAnswerValue(match[2])) {
      current = { label: match[1], raw: pyStrip(match[2]) }
      entries.push(current)
      continue
    }
    if (current !== null) {
      current.raw = pyStrip(`${current.raw}\n${line}`)
      continue
    }
    unparsed.push(line)
  }

  return { entries, unparsed: unparsed.slice(0, 50), entry_count: entries.length }
}

/** Guard against treating an ordinary numbered sentence as an answer. */
function looksLikeAnswerValue(value: string): boolean {
  const cleaned = pyStrip(value)
  if (!cleaned) return false
  if (pyCodePointLen(cleaned) > 200) return false
  if (new RegExp(`^[A-Ha-h][A-Ha-h,，、${PY_SPACE_CLASS}]*$`, 'u').test(cleaned)) return true
  if (['对', '错', '正确', '错误', '√', '×', 'T', 'F', '是', '否', 'true', 'false'].includes(cleaned)) return true
  return !['。', '？', '?'].some((suffix) => cleaned.endsWith(suffix)) || pyCodePointLen(cleaned) <= 30
}

/**
 * Match parsed answers onto question segments — as *candidates* only.
 *
 * Two matching methods are recorded per segment so the proofreader knows how much to trust the
 * pairing: `label` (the answer's position number equals the question's label) and `position` (no
 * label matched, so the answer was paired by order). Nothing here writes an answer key: the matched
 * raw answer is offered in the candidate and `answer_status_known` stays `false` until a human
 * confirms it, which is what keeps mechanical matching out of scoring.
 */
export function applyAnswerMatches(segments: ParsedSegment[], entries: AnswerEntry[]): MatchResult {
  const byLabel = new Map<string, { entry: AnswerEntry; index: number }>()
  entries.forEach((entry, index) => {
    const label = pyStrip(pyStr(entry.label, ''))
    if (!byLabel.has(label)) byLabel.set(label, { entry, index })
  })

  let matchedCount = 0
  let positionMatched = 0
  const results: Array<Record<string, unknown>> = []
  const consumed = new Set<number>()
  const materialType = QUESTION_TYPE.MATERIAL

  for (const segment of segments) {
    if (segment.question_type === materialType) {
      results.push({ matched: false, reason: 'material_parent' })
      continue
    }
    const label = pyStrip(String(segment.display_label ?? ''))
    let found = label ? byLabel.get(label) : undefined
    let method = 'label'
    if (found !== undefined && consumed.has(found.index)) {
      // The same number cannot answer two questions: a duplicated label (for example a sub-question
      // numbered inside its material) falls back to order instead of silently stealing the other
      // question's answer.
      found = undefined
    }
    if (found === undefined) {
      method = 'position'
      const index = entries.findIndex((_entry, position) => !consumed.has(position))
      found = index >= 0 ? { entry: entries[index], index } : undefined
    }
    if (found === undefined) {
      results.push({ matched: false, reason: 'no_answer_entry' })
      continue
    }
    consumed.add(found.index)
    const content = (segment.content ?? {}) as { options?: OptionPayload[]; blanks?: BlankPayload[] }
    const answer = parseAnswer(
      String(found.entry.raw ?? ''),
      segment.question_type,
      content.options ?? [],
      content.blanks ?? [],
    )
    if (!answer.known) {
      results.push({ matched: false, reason: 'answer_value_unusable', raw: found.entry.raw })
      continue
    }
    matchedCount += 1
    if (method === 'position') positionMatched += 1
    results.push({
      matched: true,
      method,
      label: pyStr(found.entry.label, ''),
      raw: found.entry.raw ?? '',
      answer_payload: answer.payload,
      parse_issue: answer.issue,
    })
  }
  const displayLabels = new Set<unknown>(segments.map((segment) => segment.display_label))
  return {
    results,
    matched_count: matchedCount,
    position_matched_count: positionMatched,
    entry_count: entries.length,
    unmatched_entry_labels: entries
      .filter((entry) => !displayLabels.has(entry.label))
      .map((entry) => pyStr(entry.label))
      .slice(0, 50),
  }
}

/**
 * Record which page each segment came from (来源页可追溯).
 *
 * The offset is the position of the segment's first line inside the document text, so a question
 * that continues across a page break is attributed to the page it starts on — the page a
 * proofreader has to open first.
 */
export function attachSourcePages(segments: ParsedSegment[], text: string, pageMap: PageMap): ParsedSegment[] {
  let cursor = 0
  for (const segment of segments) {
    const excerpt = String(segment.source_excerpt ?? '')
    const anchor = pyCodePointSlice(pyStrip(excerpt.split('\n', 1)[0]), 0, 40)
    let offset = anchor ? pyFind(text, anchor, cursor) : -1
    if (offset < 0) offset = cursor
    cursor = Math.max(cursor, offset)
    segment.source_char_start = offset
    segment.source_page_index = pageForOffset(pageMap, offset)
  }
  return segments
}

// --------------------------------------------------------------------------
// P2 batch 1 (C01): questions that continue across a page break
// --------------------------------------------------------------------------
// A line that ends with one of these has finished its sentence.
const TERMINAL_PUNCTUATION = '。！？；!?;.…'
// Trailing closing marks carry no meaning of their own when deciding that.
const CLOSING_MARKS = '”"\'’）)】》」』'
// Shapes that clearly continue the previous sentence.
const CONTINUATION_PATTERNS: RegExp[] = [
  /^[a-z]/u, // a lower-case continuation
  new RegExp(`^[（(]${PY_S_STAR}${PY_D}{1,3}${PY_S_STAR}[)）]`, 'u'), // （1）… / (2)…
  new RegExp(`^${PY_D}{1,3}${PY_S_STAR}[、,)）]`, 'u'), // 1、… without 题
  /^[，,、；;：:]/u, // starts mid-sentence
]
// Standalone headings/passages that open a page without continuing anything.
const HEADING_PATTERNS: RegExp[] = [
  new RegExp(`^${PY_S_STAR}[一二三四五六七八九十]+${PY_S_STAR}[、.．]`, 'u'), // 一、二、 section headings
  new RegExp(`^${PY_S_STAR}第${PY_S_STAR}[一二三四五六七八九十${PY_D_CLASS}]+${PY_S_STAR}[章节部分卷篇]`, 'u'),
]

function pageLines(text: string): string[] {
  return text.split('\n').map((line) => pyStrip(line)).filter((line) => line)
}

function endsWithTerminalPunctuation(line: string): boolean {
  const stripped = pyStrip(pyRstripChars(pyStrip(line ?? ''), CLOSING_MARKS))
  if (!stripped) return true
  return TERMINAL_PUNCTUATION.includes(Array.from(stripped).at(-1) as string)
}

function looksLikeStandaloneHeading(line: string): boolean {
  const text = pyStrip(line ?? '')
  if (pyCodePointLen(text) <= 30 && (text.endsWith('：') || text.endsWith(':'))) return true
  return HEADING_PATTERNS.some((pattern) => pattern.test(text))
}

/**
 * Does this line continue the previous page instead of opening a question?
 *
 * An explicit structure marker (`【题干】`, `1.`) always wins: such a line owns itself and is never
 * treated as a continuation. Otherwise an option line, a lower-case/numbered continuation or a line
 * starting mid-sentence is a continuation, and so is a plain sentence fragment — the remainder of
 * the sentence the previous page started.
 */
function looksLikeContinuation(line: string): boolean {
  const text = pyStrip(line ?? '')
  if (!text) return false
  if (SECTION_PATTERN.test(text) || LEADING_NUMBER_PATTERN.test(text)) return false
  if (OPTION_PATTERN.test(text)) return true
  if (CONTINUATION_PATTERNS.some((pattern) => pattern.test(text))) return true
  return !looksLikeStandaloneHeading(text)
}

/**
 * Page boundaries at which the running question is still open.
 *
 * A boundary is reported only when the last non-empty line of a page does *not* end a sentence
 * **and** the next page opens with a continuation; both conditions are required so an ordinary
 * question that happens to end a page is never joined.
 */
export function detectPageContinuations(pages: PageLike[]): PageContinuation[] {
  const boundaries: PageContinuation[] = []
  for (let index = 0; index + 1 < pages.length; index += 1) {
    const current = pages[index]
    const following = pages[index + 1]
    const currentLines = pageLines(String(current.text ?? ''))
    const nextLines = pageLines(String(following.text ?? ''))
    if (currentLines.length === 0 || nextLines.length === 0) continue
    const lastLine = currentLines[currentLines.length - 1]
    const firstLine = nextLines[0]
    if (endsWithTerminalPunctuation(lastLine)) continue
    if (!looksLikeContinuation(firstLine)) continue
    boundaries.push({
      from_page: intLike(current.page_index),
      to_page: intLike(following.page_index),
      last_line: pyCodePointSlice(lastLine, 0, 200),
      first_line: pyCodePointSlice(firstLine, 0, 200),
      reason: 'line_continues_across_page_break',
    })
  }
  return boundaries
}

/**
 * Split each segment into per-page spans and record page-break joins.
 *
 * The parser reads the whole document text, so a question whose stem runs over a page break is
 * already a *single* segment — what was missing was the record: `source_char_end` (where the segment
 * really ends), `source_spans` (the slice on every page it occupies, used for the source regions) and
 * `continues_on_pages` (set only when `detectPageContinuations` confirmed the break). The segment
 * keeps the page it *starts* on, so `source_position_key` still names the starting page.
 */
export function attachCrossPageContinua(
  segments: ParsedSegment[],
  text: string,
  pageMap: PageMap,
  continuations: PageContinuation[] = [],
): ParsedSegment[] {
  const confirmed = new Set(
    (continuations ?? []).map((boundary) => `${intLike(boundary.from_page)},${intLike(boundary.to_page)}`),
  )
  segments.forEach((segment, index) => {
    const start = intLike(segment.source_char_start)
    const nextStart = index + 1 < segments.length ? intLike(segments[index + 1].source_char_start) : pyCodePointLen(text)
    segment.source_char_end = Math.max(start, nextStart)
  })
  for (const segment of segments) {
    const spans = spansForSegment(segment, text, pageMap)
    segment.source_spans = spans
    const pages = spans.map((span) => Number(span.page_index))
    if (pages.length < 2) continue
    let connected = true
    for (let position = 0; position + 1 < pages.length; position += 1) {
      if (!confirmed.has(`${pages[position]},${pages[position + 1]}`)) {
        connected = false
        break
      }
    }
    if (connected) segment.continues_on_pages = pages
  }
  return segments
}

/** The part of one segment that lies on each page it occupies. */
function spansForSegment(
  segment: ParsedSegment,
  text: string,
  pageMap: PageMap,
): Array<Record<string, unknown>> {
  const start = intLike(segment.source_char_start)
  const end = intLike(segment.source_char_end ?? start)
  const spans: Array<Record<string, unknown>> = []
  for (const row of pageMap) {
    const [pageIndex, pageStart, pageEnd] = row.map((value) => Number(value))
    const spanStart = Math.max(start, pageStart)
    const spanEnd = Math.min(end, pageEnd)
    if (spanEnd <= spanStart) continue
    const spanText = pyCodePointSlice(text, spanStart, spanEnd)
    if (spans.length === 0 || pyStrip(spanText)) {
      spans.push({ page_index: pageIndex, char_start: spanStart, char_end: spanEnd, text: spanText })
    }
  }
  if (spans.length === 0) {
    spans.push({
      page_index: intLike(segment.source_page_index) || 1,
      char_start: start,
      char_end: end,
      text: pyCodePointSlice(String(segment.source_excerpt ?? ''), 0, 2000),
    })
  }
  return spans
}

function pageForOffset(pageMap: PageMap, offset: number): number {
  for (const row of pageMap) {
    const [pageIndex, start, end] = row.map((value) => Number(value))
    if (start <= offset && offset <= end) return pageIndex
  }
  // Python falls back to the last page rather than leaving the provenance missing.
  return pageMap.length > 0 ? Number(pageMap[pageMap.length - 1][0]) : 1
}

/** `str(value)` with Python's `None` spelling, used for answer labels in match results. */
function pyStr(value: unknown, whenMissing?: string): string {
  if (value === null || value === undefined) return whenMissing ?? 'None'
  return String(value)
}

/** `int(value or 0)` for the mixed numbers/strings the parser accepts from JSON. */
function intLike(value: unknown): number {
  if (value === null || value === undefined || value === '') return 0
  const parsed = Number(value)
  return Number.isFinite(parsed) ? Math.trunc(parsed) : 0
}

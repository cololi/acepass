/**
 * Paste-text structure parser — port of `backend/apps/ingestion/services/text_parser.py`.
 *
 * Two strategies, and the result is always a *candidate* a human proofreads:
 *
 * 1. an explicit template with labelled sections (recommended, lossless);
 * 2. a light heuristic for numbered question blocks.
 *
 * Neither strategy invents an answer: when a field cannot be determined it is left empty and
 * reported as an issue, which keeps unverified content out of scoring.
 *
 * The same parser serves the PDF path, so this module also carries the provenance helpers
 * (`attachSourcePages`, `detectPageContinuations`, `attachCrossPageContinua`) even though the text
 * import only uses `parsePaste` today. Every branch is pinned by `tests/golden/ingestion_text.json`,
 * which is generated by calling the Python functions directly — a mismatch here is a port defect.
 */

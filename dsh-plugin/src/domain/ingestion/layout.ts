/**
 * Layout review policy — port of `backend/apps/ingestion/services/layout.py`.
 *
 * The deterministic PDF parser never guesses a reading order and never performs OCR. Instead it
 * *classifies* each page and reports what it saw, and this module turns that classification into
 * the one thing the product rule "错误无法自动发布" needs: a **blocking** review issue on every
 * candidate that came from a page a human still has to look at.
 *
 * Keeping the mapping here (instead of inside an extractor or an HTTP route) means there is exactly
 * one place that decides which page reasons block publication, and exactly one vocabulary shared by
 * the job payload, the candidate issues and the proofreading UI.
 *
 * The file is dependency-free on purpose: the only Python semantics it needs are truthiness,
 * `int()` and `str()`, all of which are the small local helpers below. `geometry_unavailable` and
 * `too_many_fragments` mark the reading order unreliable but are **not** review blockers, so a page
 * carrying only those still imports and publishes normally.
 *
 * Every branch is pinned by `tests/golden/ingestion_layout.json`, which is generated by calling the
 * Python functions directly — a mismatch here is a port defect, not a stale expectation.
 */

// --------------------------------------------------------------------------
// Page-level reason codes produced by the extractor
// --------------------------------------------------------------------------
/** No usable text layer on this page: a scanned/image page. Never OCR'd. */
export const REASON_SCANNED = 'page_without_text_layer'
/** Two or more column bands separated by a gutter. */
export const REASON_MULTI_COLUMN = 'multi_column_layout'
/**
 * Columns were detected but their geometry is ambiguous, so the extractor kept the original order
 * instead of silently reordering the page.
 */
export const REASON_COLUMN_ORDER_AMBIGUOUS = 'column_reading_order_ambiguous'
/** Rows sharing a baseline with aligned x positions across consecutive rows. */
export const REASON_TABLE_GRID = 'table_grid_detected'
/** Math symbols or sub/superscript constructs on the page. */
export const REASON_FORMULA = 'formula_tokens_detected'
/**
 * The text visitor produced nothing, so no geometry exists for this page. This is *not* a review
 * blocker: the wording is still imported with character offsets, only the bounding box falls back
 * to the whole page.
 */
export const REASON_GEOMETRY_UNAVAILABLE = 'geometry_unavailable'
/** More fragments than the deterministic cap; the surplus was ignored. */
export const REASON_TOO_MANY_FRAGMENTS = 'too_many_fragments'

// --------------------------------------------------------------------------
// Candidate-level issue codes (what the proofreader sees)
// --------------------------------------------------------------------------
export const ISSUE_MULTI_COLUMN = 'multi_column_needs_review'
export const ISSUE_TABLE_FORMULA = 'table_or_formula_needs_review'
export const ISSUE_SCANNED = 'page_without_text_layer_needs_manual_entry'
/** Non-blocking: the question was joined across a page break. */
export const ISSUE_CROSS_PAGE = 'cross_page_question'

/** Which page reason blocks which candidate issue. */
export const REASON_TO_ISSUE: Readonly<Record<string, string>> = {
  [REASON_SCANNED]: ISSUE_SCANNED,
  [REASON_MULTI_COLUMN]: ISSUE_MULTI_COLUMN,
  [REASON_COLUMN_ORDER_AMBIGUOUS]: ISSUE_MULTI_COLUMN,
  [REASON_TABLE_GRID]: ISSUE_TABLE_FORMULA,
  [REASON_FORMULA]: ISSUE_TABLE_FORMULA,
}

/** Stable presentation order, so two identical imports report identically. */
export const ISSUE_ORDER: readonly string[] = [ISSUE_SCANNED, ISSUE_MULTI_COLUMN, ISSUE_TABLE_FORMULA]

export const ISSUE_MESSAGES: Readonly<Record<string, string>> = {
  [ISSUE_SCANNED]:
    '该题来自没有文字层的页面（扫描件/图片页）：系统不做 OCR、不猜测内容，' +
    '必须按原页人工录入或改走图片导入的人工校对路径后才能发布',
  [ISSUE_MULTI_COLUMN]:
    '该题来自多栏页面：多栏的阅读顺序无法完全确定，请对照原页确认题干、选项的先后顺序后再发布',
  [ISSUE_TABLE_FORMULA]:
    '该题所在页面包含表格网格或公式符号：表格与公式的版式可能被文本提取改变，' +
    '请对照原页逐字确认（公式按原样保留，不做“纠正”）后再发布',
}

/** A `(document_id, page_index)` pair the candidate actually came from. */
export type LayoutPageKey = readonly [documentId: string | null, pageIndex: number | string]

/** One row of the job payload's `page_diagnostics`. */
export interface PageDiagnosticRow {
  document_id?: unknown
  page_index?: unknown
  reasons?: unknown
  [field: string]: unknown
}

/** One blocking hit: the page and the page reason that produced it. */
export interface LayoutIssuePage {
  document_id: string | null
  page_index: number
  reason: string
}

export interface LayoutIssue {
  code: string
  message: string
  severity: 'blocking'
  pages: LayoutIssuePage[]
  page_indexes: number[]
  reasons: string[]
  /**
   * The oracle returns `list[dict[str, Any]]`, so an issue is an open dict at the type level even
   * though every issue this module emits carries exactly the six keys above. The index signature
   * lets the service layer fold these into the heterogeneous `review_issues` list without a cast;
   * it adds no keys at runtime.
   */
  [field: string]: unknown
}

/** The blocking issue code a page reason implies, if any. */
export function issueForReason(reason: string): string | null {
  return hasReason(reason) ? REASON_TO_ISSUE[reason] : null
}

/** Page reasons that require a human layout confirmation. */
export function reasonsNeedingReview(reasons: Iterable<string> | string | null | undefined): string[] {
  return reasonsNeedingReviewFrom(reasons)
}

/** Same rule for an untyped `row["reasons"]` straight out of the job payload. */
function reasonsNeedingReviewFrom(reasons: unknown): string[] {
  const seen: string[] = []
  for (const reason of iterReasons(reasons)) {
    if (hasReason(reason) && !seen.includes(reason)) seen.push(reason)
  }
  return seen
}

export function needsReview(reasons: Iterable<string> | string | null | undefined): boolean {
  return reasonsNeedingReview(reasons).length > 0
}

export function issueCodesForReasons(reasons: Iterable<string> | string | null | undefined): string[] {
  const codes: string[] = []
  for (const reason of reasonsNeedingReview(reasons)) {
    const code = REASON_TO_ISSUE[reason]
    if (!codes.includes(code)) codes.push(code)
  }
  return codes
}

/**
 * Blocking issues for a candidate whose source pages need layout review.
 *
 * `pages` is the set of `(document_id, page_index)` the candidate actually came from, so a
 * job-level diagnosis only blocks the candidates that touch the suspicious page — a clean page in
 * the same file still imports and publishes normally.
 */
export function layoutReviewIssues(input: {
  pageDiagnostics: Iterable<PageDiagnosticRow> | null
  pages: Iterable<LayoutPageKey>
}): LayoutIssue[] {
  // `wanted` is a set of `(str(document_id) | None, int(page_index))`. A nested map is the exact
  // equivalent for two scalar components (a composite string key would blur `null` and numbers).
  const wanted = new Map<string | null, Set<number>>()
  for (const [rawDocumentId, rawPageIndex] of input.pages) {
    const documentId = rawDocumentId === null || rawDocumentId === undefined ? null : pyStr(rawDocumentId)
    const pageIndex = pyInt(rawPageIndex)
    const indexes = wanted.get(documentId)
    if (indexes === undefined) wanted.set(documentId, new Set([pageIndex]))
    else indexes.add(pageIndex)
  }
  if (wanted.size === 0) return []

  const hits = new Map<string, LayoutIssuePage[]>()
  for (const row of input.pageDiagnostics ?? []) {
    const rawDocumentId = row['document_id']
    const documentId = rawDocumentId === undefined || rawDocumentId === null ? null : pyStr(rawDocumentId)
    const rawPageIndex = row['page_index']
    // `int(row.get("page_index") or 0)`: a missing/None/empty index reads as page 0.
    const pageIndex = pyInt(pyTruthy(rawPageIndex) ? rawPageIndex : 0)
    if (!wanted.get(documentId)?.has(pageIndex)) continue
    for (const reason of reasonsNeedingReviewFrom(row['reasons'])) {
      const code = REASON_TO_ISSUE[reason]
      let entries = hits.get(code)
      if (entries === undefined) {
        entries = []
        hits.set(code, entries)
      }
      entries.push({ document_id: documentId, page_index: pageIndex, reason })
    }
  }

  const issues: LayoutIssue[] = []
  for (const code of ISSUE_ORDER) {
    const entries = hits.get(code)
    if (entries === undefined || entries.length === 0) continue
    issues.push({
      code,
      message: ISSUE_MESSAGES[code],
      severity: 'blocking',
      pages: entries,
      page_indexes: entries.map((entry) => entry.page_index),
      reasons: sortedUnique(entries.map((entry) => entry.reason)),
    })
  }
  return issues
}

// --------------------------------------------------------------------------
// Python semantics (kept local so this module stays a leaf)
// --------------------------------------------------------------------------

/** Python dict-key membership (`reason in REASON_TO_ISSUE`) — own keys only, like a dict. */
function hasReason(reason: unknown): reason is string {
  return typeof reason === 'string' && Object.hasOwn(REASON_TO_ISSUE, reason)
}

/** Python `for reason in reasons or []` for the shapes a JSON payload can carry. */
function iterReasons(value: unknown): readonly string[] {
  if (!pyTruthy(value)) return []
  if (typeof value === 'string') return Array.from(value)
  if (Array.isArray(value)) return value as readonly string[]
  if (typeof value === 'object') return Object.keys(value as object)
  throw new TypeError(`'${pyTypeName(value)}' object is not iterable`)
}

/** Python truthiness, for the `or []` / `or 0` fallbacks in the oracle. */
function pyTruthy(value: unknown): boolean {
  if (value === null || value === undefined) return false
  if (typeof value === 'string') return value.length > 0
  if (Array.isArray(value)) return value.length > 0
  if (typeof value === 'number') return value !== 0
  if (typeof value === 'boolean') return value
  if (typeof value === 'object') return Object.keys(value as object).length > 0
  return true
}

/**
 * Python `int(value)` for the scalar shapes `page_index` can arrive as.
 *
 * Accepted forms: booleans (`int(True) == 1`), numbers (truncated toward zero, `int(2.9) == 2`) and
 * strings with Python's `int()` grammar — surrounding whitespace, an optional sign and single
 * underscores between digits. Unicode decimal digits are not decoded (page indexes are stored as
 * integers); a literal outside that grammar raises instead of silently reading as 0, exactly like
 * the oracle raises `ValueError`/`TypeError` instead of guessing.
 */
function pyInt(value: unknown): number {
  if (typeof value === 'boolean') return value ? 1 : 0
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`invalid literal for int(): ${value}`)
    return Math.trunc(value)
  }
  if (typeof value === 'string') {
    const match = /^([+-]?)(\d+(?:_\d+)*)$/.exec(value.trim())
    if (match === null) throw new Error(`invalid literal for int() with base 10: ${JSON.stringify(value)}`)
    const magnitude = Number(match[2].replaceAll('_', ''))
    return match[1] === '-' ? -magnitude : magnitude
  }
  throw new TypeError(
    `int() argument must be a string, a bytes-like object or a number, not '${pyTypeName(value)}'`,
  )
}

/** Python `str(value)` for the scalar `document_id` shapes (`None` never reaches this helper). */
function pyStr(value: unknown): string {
  if (typeof value === 'string') return value
  if (typeof value === 'boolean') return value ? 'True' : 'False'
  if (typeof value === 'number') return String(value)
  if (value === null || value === undefined) return 'None'
  // Python's `str()` on a list/dict is `repr()`, which the app never stores in a document id.
  return String(value)
}

/** Python `sorted(set(values))` — `sorted()` on strings orders by code unit for these ASCII codes. */
function sortedUnique(values: readonly string[]): string[] {
  return [...new Set(values)].sort()
}

function pyTypeName(value: unknown): string {
  if (value === null || value === undefined) return 'NoneType'
  if (typeof value === 'boolean') return 'bool'
  if (typeof value === 'number') return Number.isInteger(value) ? 'int' : 'float'
  if (typeof value === 'string') return 'str'
  if (Array.isArray(value)) return 'list'
  return 'dict'
}

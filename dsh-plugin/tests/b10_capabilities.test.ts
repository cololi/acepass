test('b10: a disputed answer sends graded attempts to review and invalidates their evidence', () => {
  const h = harness()
  try {
    const seed = h.makeQuestion('D1')
    const { itemIds } = h.startSession([seed])
    const attemptId = h.answer(itemIds[0])
    // The evidence the dispute is about has to exist before it can be invalidated.
    const rebuilt = rebuildEvidenceForAttempt(h.db, attemptId, NOW)
    assert.ok(rebuilt > 0, 'a graded attempt produces evidence rows')
    const activeBefore = findRows(h.db, 'practice_learning_evidence', { attempt_id: attemptId, is_active: true })
    assert.equal(activeBefore.length, rebuilt)

    const reason = String(GOLDEN.dispute.comment).replace(/^答案争议：/, '')
    assert.equal(reason, GOLDEN.dispute.invalidation_reason, 'the vector carries one reason for both fields')
    const result = disputeAnswerKeyVersion(h.db, h.userId, h.projectId, seed.answerKeyId, reason, NOW + MINUTE)

    // The answer stops being usable immediately.
    const answerRow = row(h.db, 'question_bank_answer_key_version', seed.answerKeyId)
    assert.equal(answerRow.verification_status, 'disputed')
    assert.equal(answerRow.is_disputed, true)
    assert.equal(answerRow.dispute_reason, reason)
    assert.equal(result.answer.dispute_reason, reason, 'the returned snapshot is the updated row')

    // The editorial action is audited.
    const revisions = findRows(h.db, 'audit_content_revision', {
      entity_type: 'answer_key_version',
      entity_id: seed.answerKeyId,
      action: 'dispute',
    })
    assert.equal(revisions.length, 1)
    assert.equal(revisions[0].reason, reason)
    assert.equal(revisions[0].project_id, h.projectId)

    // The attempt keeps its raw answer but points at a new, reviewing grade event.
    const attempt = row(h.db, 'practice_attempt', attemptId)
    assert.deepEqual(attempt.raw_answer, { type: 'single_choice', selected_option_id: 'opt_b' })
    assert.equal(result.affected, 1)
    assert.equal(Number(attempt.grading_revision), 2)
    const events = findRows(h.db, 'practice_grade_event', { attempt_id: attemptId }).sort(
      (a, b) => Number(a.grading_revision) - Number(b.grading_revision),
    )
    assert.equal(events.length, 2)
    const [previous, invalidation] = events
    assert.equal(previous.kind, 'initial')
    assert.equal(previous.is_superseded, true, 'the superseded event is kept, not deleted')
    assert.equal(String(attempt.current_grade_event_id), String(invalidation.id))
    assert.equal(invalidation.kind, 'invalidation')
    assert.equal(invalidation.status, 'pending_review')
    assert.equal(invalidation.method, 'mixed')
    assert.equal(Number(invalidation.grading_revision), 2)
    assert.equal(invalidation.confirmed_score, null)
    assert.equal(String(invalidation.max_score), '2.00')
    assert.equal(String(invalidation.pending_max_score), '2.00')
    assert.equal(invalidation.is_fully_confirmed, false)
    assert.equal(String(invalidation.supersedes_id), String(previous.id))
    assert.equal(invalidation.comment, `答案争议：${reason}`)
    assert.equal(invalidation.invalidation_reason, reason)
    assert.equal(invalidation.rule_version, previous.rule_version)
    assert.deepEqual(invalidation.rule_snapshot, previous.rule_snapshot)
    assert.equal(String(invalidation.answer_key_version_id), seed.answerKeyId)
    assert.equal(String(invalidation.rubric_version_id), String(previous.rubric_version_id))
    assert.equal(String(invalidation.spec_version_id), String(previous.spec_version_id))
    assert.equal(String(invalidation.grader_id), h.userId)
    assert.equal(invalidation.grader_is_self, false)
    // Every part is neutralised: no score, pending review, and the reason Django writes.
    const parts = invalidation.parts as Record<string, unknown>[]
    assert.equal(parts.length, (previous.parts as unknown[]).length)
    assert.ok(parts.length > 0)
    for (const part of parts) {
      assert.equal(part.score, null)
      assert.equal(part.status, 'pending_review')
      assert.equal(part.method, null)
      assert.deepEqual(part.detail, { reason: '答案进入争议，原判分不再作为正式分数' })
      assert.deepEqual(
        Object.keys(part).sort(),
        ['detail', 'max_score', 'method', 'part_id', 'score', 'status'],
        'the part shape is the frozen one',
      )
    }

    // The Django vector: same event shape, same comment and reason.
    const goldenEvent = GOLDEN.dispute.event
    assert.equal(invalidation.kind, goldenEvent.kind)
    assert.equal(invalidation.status, goldenEvent.status)
    assert.equal(invalidation.method, goldenEvent.method)
    assert.equal(invalidation.confirmed_score, goldenEvent.confirmed_score)
    assert.equal(String(invalidation.max_score), goldenEvent.max_score)
    assert.equal(String(invalidation.pending_max_score), goldenEvent.pending_max_score)
    assert.equal(invalidation.is_fully_confirmed, goldenEvent.is_fully_confirmed)
    assert.equal(invalidation.is_superseded, goldenEvent.is_superseded)
    assert.equal(invalidation.grader_is_self, goldenEvent.grader_is_self)
    assert.equal(invalidation.rule_version, goldenEvent.rule_version)
    assert.deepEqual(invalidation.parts, goldenEvent.parts)
    assert.deepEqual(Object.keys(parts[0]).sort(), GOLDEN.dispute.part_keys)
    assert.equal(invalidation.comment, GOLDEN.dispute.comment)
    assert.equal(invalidation.invalidation_reason, GOLDEN.dispute.invalidation_reason)
    assert.equal(Number(invalidation.grading_revision) - Number(previous.grading_revision), GOLDEN.dispute.grading_revision_delta)
    assert.equal(previous.is_superseded, GOLDEN.dispute.previous_is_superseded)
    assert.deepEqual(invalidation.rule_snapshot, previous.rule_snapshot)
    assert.equal(GOLDEN.dispute.rule_snapshot_copied, true)

    // One outbox event tells the projection to stop counting the evidence.
    const eventsOut = findRows(h.db, 'audit_outbox_event', { topic: 'projection.rebuild_after_answer_change' })
    assert.equal(eventsOut.length, 1)
    assert.deepEqual(eventsOut[0].payload, { answer_key_version_id: seed.answerKeyId, affected_attempts: 1 })
    const epochSeconds = Number(NOW + MINUTE) / 1e6
    assert.equal(eventsOut[0].dedupe_key, `answer-change:${seed.answerKeyId}:${Math.trunc(epochSeconds)}`)

    // The consumer body: the evidence rows become inactive with Django's reason.
    const vector = GOLDEN.evidence_invalidation
    assert.equal(rebuilt, vector.rows_per_attempt, 'the attempt projects six dimensions')
    const invalidated = invalidateEvidenceForAnswerVersion(h.db, seed.answerKeyId, NOW + 2n * MINUTE)
    assert.equal(invalidated, vector.returned)
    const after = findRows(h.db, 'practice_learning_evidence', { attempt_id: attemptId })
    assert.equal(after.length, rebuilt, 'rows are invalidated, never deleted')
    for (const evidence of after) {
      assert.equal(evidence.is_active, false)
      assert.equal(evidence.invalidated_at, NOW + 2n * MINUTE)
      assert.equal(evidence.invalidated_reason, vector.invalidated_reason)
      assert.equal(evidence.invalidated_reason, ANSWER_DISPUTED_INVALIDATION_REASON)
      assert.equal(evidence.invalidated_at !== null, vector.invalidated_at_set)
    }
    assert.equal(after.filter((evidence) => evidence.is_active).length, vector.active_after)
    // A second run finds nothing active and reports 0, not an error.
    assert.equal(invalidateEvidenceForAnswerVersion(h.db, seed.answerKeyId, NOW + 3n * MINUTE), vector.second_call)
    // A different answer version is untouched.
    assert.equal(invalidateEvidenceForAnswerVersion(h.db, 'missing-answer', NOW), 0)
  } finally {
    h.close()
  }
})


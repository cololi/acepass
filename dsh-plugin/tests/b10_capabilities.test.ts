test('b10: expiring an overdue mock exam ends it at the deadline and enqueues once', () => {
  const h = harness()
  try {
    const seed = h.makeQuestion('E1')
    const { sessionId, itemIds } = h.startSession([seed], 'mock_exam', { duration_minutes: 30 })
    h.answer(itemIds[0])
    const active = row(h.db, 'practice_session', sessionId)
    const deadline = active.exam_deadline as Instant
    assert.equal(deadline, NOW + 30n * MINUTE)

    // Before the deadline nothing happens.
    const early = expireSessionIfDue(h.db, active, deadline - 1n)
    assert.equal(early.status, 'active')
    assert.equal(countRows(h.db, 'audit_outbox_event', { topic: 'learning.on_session_finished' }), 0)

    const noticedAt = deadline + 5n * MINUTE
    const expiryVector = GOLDEN.mock_exam_expiry
    assert.equal(early.status, expiryVector.before_deadline_status)
    const expired = expireSessionIfDue(h.db, row(h.db, 'practice_session', sessionId), noticedAt)
    assert.equal(expired.status, 'finished')
    assert.equal(expired.finished_at === deadline, expiryVector.finished_at_is_deadline, 'the exam ends at its deadline, not when noticed')
    assert.equal(expired.revealed_at === deadline, expiryVector.revealed_at_is_deadline)
    assert.equal(expired.expired_at === noticedAt, expiryVector.expired_at_is_the_observed_moment)
    assert.equal(countRows(h.db, 'audit_outbox_event', { topic: 'learning.on_session_finished' }), expiryVector.events)

    // A second sweep (every read path runs one) produces no second transition or event.
    const again = expireSessionIfDue(h.db, row(h.db, 'practice_session', sessionId), noticedAt + MINUTE)
    assert.equal(again.status, 'finished')
    assert.equal(again.expired_at, noticedAt)
    assert.equal(
      countRows(h.db, 'audit_outbox_event', { topic: 'learning.on_session_finished' }),
      expiryVector.second_sweep_events,
    )

    // A manual finish after the sweep is the same no-op.
    finishSession(h.db, h.userId, sessionId, noticedAt + HOUR)
    assert.equal(countRows(h.db, 'audit_outbox_event', { topic: 'learning.on_session_finished' }), 1)
  } finally {
    h.close()
  }
})


const GOLDEN = JSON.parse(
  readFileSync(new URL('./golden/b10_capabilities.json', import.meta.url), 'utf8'),
) as Record<string, any>

const NOW = parseInstant('2026-11-01T09:00:00+00:00')
const MINUTE = 60_000_000n
const HOUR = 3_600_000_000n

function completeRow(table: string, overrides: Record<string, unknown>): Record<string, unknown> {
  const definition = TABLES.find((entry) => entry.name === table)
  assert.ok(definition, `unknown table ${table}`)
  const foreignKeys = new Map(definition.foreignKeys.map((fk) => [fk.column, fk]))
  const row: Record<string, unknown> = {}
  for (const column of definition.columns) {
    if (column.primaryKey || column.name in overrides) continue
    if (!column.notNull) continue
    const fk = foreignKeys.get(column.name)
    if (fk) {
      row[column.name] = `fk-${fk.refTable}`
      continue
    }
    row[column.name] = column.json
      ? {}
      : column.kind === 'datetime'
        ? NOW
        : column.kind === 'int' || column.kind === 'bool'
          ? 0
          : ''
  }
  Object.assign(row, overrides)
  return row
}

const SINGLE_CONTENT = {
  blocks: [{ kind: 'text', text: '1+1 等于几？' }],
  options: [
    { id: 'opt_a', label: 'A', blocks: [{ kind: 'text', text: '1' }] },
    { id: 'opt_b', label: 'B', blocks: [{ kind: 'text', text: '2' }] },
  ],
}

interface Seed {
  questionId: string
  versionId: string
  answerKeyId: string
}

function harness() {
  const handle = openStore({ path: ':memory:' })
  const db: DatabaseSync = handle.db
  const user = insertRow(
    db,
    'accounts_user',
    completeRow('accounts_user', { email: 'b10@example.com', display_name: 'B10', date_joined: NOW }),
    { now: NOW },
  )
  const userId = String(user.id)
  const project = createProject(db, userId, { name: 'B10 项目' }, NOW)
  const projectId = String(project.id)
  const subject = createSubject(db, userId, projectId, { name: '科目', total_score: '100', pass_score: '60' }, NOW)
  const subjectId = String(subject.id)
  const spec = createSpecVersion(
    db,
    userId,
    projectId,
    {
      subject_id: subjectId,
      name: '规范',
      total_score: '100',
      pass_score: '60',
      question_type_rules: { single_choice: { default_max_score: '2' } },
    },
    NOW,
  )
  publishSpecVersion(db, userId, projectId, String(spec.id), NOW)
  const syllabus = createSyllabusVersion(
    db,
    userId,
    projectId,
    { subject_id: subjectId, name: '大纲', version_label: '2026' },
    NOW,
  )
  publishSyllabusVersion(db, userId, projectId, String(syllabus.id), NOW)
  const node = createNode(
    db,
    userId,
    projectId,
    { syllabus_version_id: String(syllabus.id), canonical_name: '考点一', kind: 'point', display_order: 0 },
    NOW,
  )
  const nodeId = String(node.id)

  /** One published single-choice question, mapped to the shared node, with a checked answer. */
  const makeQuestion = (label: string): Seed => {
    const question = createQuestion(db, userId, { subjectId, displayLabel: label }, NOW)
    const draft = createQuestionRevision(
      db,
      userId,
      projectId,
      String(question.id),
      { question_type: 'single_choice', content: SINGLE_CONTENT, practice_max_score: '2.00' },
      NOW,
    )
    const versionId = String(draft.id)
    const answer = createAnswerKeyVersion(
      db,
      userId,
      projectId,
      versionId,
      {
        answerPayload: { kind: 'single_choice', correct_option_id: 'opt_b' },
        sourceType: 'user',
        verificationStatus: 'checked',
        checkBasis: '教材第 1 章',
      },
      NOW,
    )
    replaceKnowledgeMappings(db, projectId, versionId, [{ node_id: nodeId, is_primary: true, score_weight: '1' }], {
      actorId: userId,
      now: NOW,
    })
    publishQuestionVersion(db, userId, projectId, versionId, { now: NOW })
    return { questionId: String(question.id), versionId, answerKeyId: String(answer.id) }
  }

  const startSession = (
    seeds: Seed[],
    mode = 'practice',
    extra: Record<string, unknown> = {},
  ): { sessionId: string; itemIds: string[] } => {
    const created = createSession(
      db,
      userId,
      projectId,
      {
        subject_id: subjectId,
        mode,
        question_ids: seeds.map((seed) => seed.questionId),
        ...extra,
      },
      NOW,
    )
    const items = findRows(db, 'practice_session_item', { session_id: String(created.id) })
    return { sessionId: String(created.id), itemIds: items.map((row) => String(row.id)) }
  }

  /**
   * Present, then submit one minute later.
   *
   * The one minute is not decoration: the evidence rule refuses a "trusted timing" dimension for an
   * attempt with `elapsed_ms === 0` (`缺少可信用时记录`), so a same-instant submit would make the
   * projection assertions vacuous.
   */
  const answer = (itemId: string, correct = true): string => {
    presentItem(db, userId, itemId, NOW)
    const submitted = submitAttempt(
      db,
      userId,
      itemId,
      {
        raw_answer: { type: 'single_choice', selected_option_id: correct ? 'opt_b' : 'opt_a' },
      },
      NOW + MINUTE,
    )
    return String(submitted.attempt.id)
  }

  return {
    db,
    userId,
    projectId,
    subjectId,
    nodeId,
    makeQuestion,
    startSession,
    answer,
    close: handle.close,
  }
}

/** The row of one table by id, asserted to exist. */
function row(db: DatabaseSync, table: string, id: string): Record<string, unknown> {
  const found = findOne(db, table, { id })
  assert.ok(found !== null, `${table} ${id} must exist`)
  return found
}


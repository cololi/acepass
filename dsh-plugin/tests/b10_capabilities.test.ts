// ---------------------------------------------------------------------------

test('b10: a repeated dispute counts the attempts and creates no second invalidation event', () => {
  const h = harness()
  try {
    const seed = h.makeQuestion('D2')
    const first = h.startSession([seed])
    const second = h.startSession([seed])
    const attemptA = h.answer(first.itemIds[0])
    const attemptB = h.answer(second.itemIds[0], false)
    assert.equal(countRows(h.db, 'practice_grade_event', { attempt_id: attemptA }), 1)
    assert.equal(countRows(h.db, 'practice_grade_event', { attempt_id: attemptB }), 1)

    const reason = '同一答案版本被再次质疑'
    const one = disputeAnswerKeyVersion(h.db, h.userId, h.projectId, seed.answerKeyId, reason, NOW + MINUTE)
    assert.equal(one.affected, GOLDEN.dispute.affected_for_two_attempts, 'both attempts froze this answer version')
    assert.equal(countRows(h.db, 'practice_grade_event', { attempt_id: attemptA }), 2)
    assert.equal(countRows(h.db, 'practice_grade_event', { attempt_id: attemptB }), 2)

    // Same wall-clock second: the dedupe key repeats, so the event row is reused.
    const eventsAfterFirst = countRows(h.db, 'practice_grade_event', { attempt_id: attemptA })
    const two = disputeAnswerKeyVersion(h.db, h.userId, h.projectId, seed.answerKeyId, reason, NOW + MINUTE + 10n)
    assert.equal(two.affected, GOLDEN.repeat_dispute.affected, 'already-pending attempts still count')
    assert.equal(countRows(h.db, 'practice_grade_event', { attempt_id: attemptA }), 2, 'no second event')
    assert.equal(countRows(h.db, 'practice_grade_event', { attempt_id: attemptB }), 2)
    assert.equal(
      countRows(h.db, 'practice_grade_event', { attempt_id: attemptA }) - eventsAfterFirst,
      GOLDEN.repeat_dispute.events_added,
      'a repeated dispute adds no grade event',
    )
    assert.equal(
      findRows(h.db, 'audit_outbox_event', { topic: 'projection.rebuild_after_answer_change' }).length,
      GOLDEN.answer_change_dedupe.same_second_events,
      'same-second disputes answer to one event',
    )

    // A later second produces a new dedupe key: the Django key is second-granular, not per-answer.
    const three = disputeAnswerKeyVersion(h.db, h.userId, h.projectId, seed.answerKeyId, reason, NOW + 2n * MINUTE)
    assert.equal(three.affected, GOLDEN.repeat_dispute.affected)
    const answerChangeEvents = findRows(h.db, 'audit_outbox_event', { topic: 'projection.rebuild_after_answer_change' })
    assert.equal(answerChangeEvents.length, GOLDEN.answer_change_dedupe.next_second_events)
    // `answer-change:<answer_key_version_id>:<epoch-seconds>` — whole seconds, as Django formats it.
    for (const event of answerChangeEvents) {
      assert.match(String(event.dedupe_key), new RegExp(`^answer-change:${seed.answerKeyId}:\\d+$`))
    }
    const firstEvent = answerChangeEvents[0]
    assert.deepEqual(Object.keys(firstEvent.payload as object).sort(), ['affected_attempts', 'answer_key_version_id'])

    // The direct service behaves the same way when called without the wrapper.
    assert.equal(handleAnswerDispute(h.db, seed.answerKeyId, h.userId, reason, NOW + 3n * MINUTE), 2)
    assert.equal(countRows(h.db, 'practice_grade_event', { attempt_id: attemptA }), 2)
  } finally {
    h.close()
  }
})


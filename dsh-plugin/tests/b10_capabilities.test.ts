test('b10: finishing a task session rebuilds evidence for every attempt, refreshes state, completes the task and reveals grading', () => {
  const h = harness()
  try {
    const seeds = [h.makeQuestion('S1'), h.makeQuestion('S2'), h.makeQuestion('S3')]
    // A task with no bound question keeps the explicit question list (Django: `if task.question_id`).
    const task = insertRow(
      h.db,
      'learning_study_task',
      completeRow('learning_study_task', {
        user_id: h.userId,
        project_id: h.projectId,
        subject_id: h.subjectId,
        task_kind: 'paired_immediate',
        status: 'pending',
        question_id: null,
        knowledge_node_id: h.nodeId,
      }),
      { now: NOW },
    )
    const { sessionId, itemIds } = h.startSession(seeds, 'practice', { task_id: String(task.id) })
    const session = row(h.db, 'practice_session', sessionId)
    assert.equal(session.mode, 'verification', 'the task kind decides the mode')
    assert.equal(String(session.origin_task_id), String(task.id))
    assert.equal(itemIds.length, 3)

    const attemptIds = itemIds.map((itemId) => h.answer(itemId))
    assert.equal(countRows(h.db, 'practice_learning_evidence', {}), 0, 'nothing is projected before the end')

    const finishedAt = NOW + 5n * MINUTE
    const finishVector = GOLDEN.session_finish
    const finished = finishSession(h.db, h.userId, sessionId, finishedAt)
    assert.equal(finished.status, finishVector.status)
    assert.equal(finished.finished_at, finishedAt)
    assert.equal(finished.revealed_at, finishedAt, 'a verification reveals its grading when it ends')
    assert.equal(finished.revealed_at === finished.finished_at, finishVector.revealed_equals_finished)
    assert.equal(finished.expired_at, null)

    // The task that opened the run is completed, with the session's own end as `completed_at`.
    const completed = row(h.db, 'learning_study_task', String(task.id))
    assert.equal(completed.status, finishVector.task_status)
    assert.equal(completed.completed_at, finishedAt)
    assert.equal(completed.completed_at === finished.finished_at, finishVector.task_completed_at_equals_finished)

    // Exactly one event, addressed to the session.
    const events = findRows(h.db, 'audit_outbox_event', { topic: finishVector.event_topic })
    assert.equal(events.length, finishVector.events)
    assert.deepEqual(events[0].payload, { session_id: sessionId })
    assert.deepEqual(Object.keys(events[0].payload as object).sort(), finishVector.payload_keys)
    assert.equal(events[0].dedupe_key, `session-finished:${sessionId}`)

    // The consumer body: every attempt of the session is rebuilt, then its nodes refreshed.
    const refreshVector = GOLDEN.session_refresh
    const refreshed = refreshSessionStates(h.db, sessionId, finishedAt)
    assert.equal(refreshed, refreshVector.returned, 'one node per attempt (all three map to the same node)')
    assert.equal(attemptIds.length, refreshVector.attempts)
    attemptIds.forEach((attemptId, index) => {
      const evidence = findRows(h.db, 'practice_learning_evidence', { attempt_id: attemptId })
      assert.equal(evidence.length, refreshVector.evidence_per_attempt[index])
      for (const row_ of evidence) {
        assert.equal(row_.is_active, true)
        assert.equal(Number(row_.grade_revision), 1)
      }
    })
    const state = findOne(h.db, 'learning_knowledge_state', { user_id: h.userId, node_id: h.nodeId })
    assert.ok(state !== null, 'the projection wrote a state row')
    assert.equal(state!.as_of, finishedAt)
    for (const [field, expected] of Object.entries(refreshVector.state)) {
      assert.equal(state![field], expected, `projected state ${field}`)
    }

    // Finishing again is a no-op: same row, no second event, task untouched.
    const again = finishSession(h.db, h.userId, sessionId, finishedAt + HOUR)
    assert.equal(again.status, 'finished')
    assert.equal(again.finished_at, finishedAt, 'the first finish wins')
    assert.equal(
      findRows(h.db, 'audit_outbox_event', { topic: 'learning.on_session_finished' }).length,
      1,
      'a repeated finish must not enqueue again',
    )
  } finally {
    h.close()
  }
})


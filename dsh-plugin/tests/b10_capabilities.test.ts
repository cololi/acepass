test('b10: an answer from another project (or an unknown id) is a 404, not a 403', () => {
  const h = harness()
  try {
    const seed = h.makeQuestion('D3')
    const stranger = insertRow(
      h.db,
      'accounts_user',
      completeRow('accounts_user', { email: 'stranger@example.com', display_name: '别人', date_joined: NOW }),
      { now: NOW },
    )
    assert.throws(
      () => disputeAnswerKeyVersion(h.db, String(stranger.id), h.projectId, seed.answerKeyId, 'x', NOW),
      (error: unknown) => error instanceof ScopeViolation && (error as ScopeViolation).statusCode === 404,
    )
    assert.throws(
      () => disputeAnswerKeyVersion(h.db, h.userId, h.projectId, 'missing-answer', 'x', NOW),
      ScopeViolation,
    )
    // Neither refused call left a trace.
    assert.equal(countRows(h.db, 'audit_content_revision', { action: 'dispute' }), 0)
    assert.equal(countRows(h.db, 'audit_outbox_event', {}), 0)
  } finally {
    h.close()
  }
})


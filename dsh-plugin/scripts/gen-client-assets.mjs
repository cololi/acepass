/**
 * Generate the client's stylesheet assets.
 *
 * The browser bundle cannot reference files next to the package (no asset route is mounted for an
 * out-of-tree plugin here), so KaTeX's stylesheet is inlined **with its woff2 fonts as data URLs**.
 * Only `.woff2` is rewritten: it is the one format every current browser uses, and the woff/ttf
 * fallbacks in the same file stay relative and simply 404 in environments without them.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'

const katexRoot = '../frontend/node_modules/katex/dist'
const css = readFileSync(join(katexRoot, 'katex.min.css'), 'utf8')
const inlined = css.replace(/url\((["']?)fonts\/([A-Za-z0-9_-]+\.woff2)\1\)/g, (_match, _quote, file) => {
  const bytes = readFileSync(join(katexRoot, 'fonts', file))
  return `url(data:font/woff2;base64,${bytes.toString('base64')})`
})
const out = 'src/client/generated/katex-css.ts'
mkdirSync(dirname(out), { recursive: true })
writeFileSync(
  out,
  `/** Generated by scripts/gen-client-assets.mjs — do not edit. KaTeX stylesheet with woff2 fonts inlined. */\nexport const KATEX_CSS = ${JSON.stringify(inlined)}\n`,
)
console.log(`${out} ${inlined.length} chars`)

#!/usr/bin/env python
"""Empirical HTTP probe for the PDF batch import (B4).

Operations covered, all through the real Ninja router against a real PostgreSQL test database:

* O09 ``POST /api/v1/projects/{project_id}/imports/pdf``   (native-text PDF batch import)
* O17 ``POST /api/v1/projects/{project_id}/import-candidates/{id}/layout-confirm``
  (the layout gate that PDF candidates have to pass before publishing)
* O15 ``PATCH /api/v1/projects/{project_id}/import-candidates/{id}`` and
  O18 ``POST  .../import-candidates/{id}/publish`` are driven only as the precondition of O17:
  a candidate has to be proofread-ready before "publish refuses it" means anything.

Nothing here asserts what the API *should* do. Every case records the request shape (method, path,
multipart field summary with file names / declared content types / byte sizes / sha256, idempotency
key), the status, the response headers, the raw JSON payload, the row deltas the call left behind,
every page fact of every fixture the call stored and every candidate's review issues, regions and
answer match.

Determinism rules (the JSON is generated twice and compared by sha256):

* every UUID that would reach the payload is replaced by a symbolic name; an unknown one is
  auto-named ``REF_nnn`` in first-appearance order and re-named later when its fixture gets a
  symbolic name;
* every timestamp is replaced by ``"<now>"`` (``created_at``, ``updated_at``,
  ``layout_review_confirmed_at``, ...), because those are real clocks;
* object keys are reduced to a *shape* (segment count / namespace / token length / suffix);
* PDF fixtures are generated by ``tests/support/pdf_builder.py`` (a minimal Type0/Identity-H writer)
  from fixed page text, so every run produces the same bytes; the two encrypted fixtures are built
  with a fixed owner password and a fixed algorithm (``RC4-128``), which pypdf derives from the
  document id and therefore also reproduces byte for byte.

Usage (from ``dsh-plugin/``)::

    ../backend/.venv/bin/python scripts/probe_ingestion_b4.py

Writes ``docs/dsh-migration/13-ingestion-b4-probe.json`` only; the markdown report is hand written
from that evidence.
"""


def register_job_rows(case_id: str, job: ImportJob) -> None:
    """Give an import's job / documents / assets / candidates / regions stable names before dumping."""
    reg(f"JOB_{case_id}", job)
    documents = list(job.documents.order_by("created_at"))
    for index, document in enumerate(documents, start=1):
        suffix = "" if len(documents) == 1 else f"_{index}"
        name_unless_real(str(document.id), f"DOCUMENT_{case_id}{suffix}")
        if document.asset_id:
            name_unless_real(str(document.asset_id), f"ASSET_OF_DOCUMENT_{case_id}{suffix}")
    candidates = list(job.candidates.order_by("created_at"))
    for index, candidate in enumerate(candidates, start=1):
        suffix = "" if len(candidates) == 1 else f"_{index}"
        reg(f"CANDIDATE_{case_id}{suffix}", candidate)
        for region_index, region in enumerate(candidate.source_regions.all(), start=1):
            name_unless_real(str(region.id), f"REGION_{case_id}{suffix}_{region_index}")


def job_facts(job: ImportJob) -> dict:
    documents = list(job.documents.order_by("created_at"))
    return {
        "job": job_row(job),
        "documents": [document_row(document) for document in documents],
        "fixture_pages": [page_facts(document, job) for document in documents],
        "page_diagnostics": page_diagnostics_rows(job),
        "candidates": [candidate_row(candidate) for candidate in job.candidates.order_by("created_at")],
    }


def paper_facts(job: ImportJob, case_id: str) -> dict:
    """The paper occurrence one import registered, when it registered one."""
    candidate = job.candidates.order_by("created_at").first()
    revision = candidate.paper_revision if candidate is not None else None
    if revision is None:
        return {"paper": None, "revisions": [], "paper_items": []}
    paper = revision.paper
    reg(f"PAPER_{case_id}", paper)
    revisions = list(paper.revisions.order_by("revision"))
    for row in revisions:
        reg(f"REVISION_{case_id}_{row.revision}", row)
    return {
        "paper": paper_row(paper),
        "revisions": [revision_row(row) for row in revisions],
        "paper_items": [item for row in revisions for item in paper_item_rows(row)],
    }


def register_publication_ids(prefix: str, candidate: ImportCandidate) -> None:
    """Name the rows a publish wrote, so the JSON never carries an anonymous publication id."""
    for label, value in (
        ("QUESTION", candidate.publication_question_id),
        ("VERSION", candidate.publication_version_id),
        ("PAPER_ITEM", candidate.publication_paper_item_id),
    ):
        if value is not None:
            reg(f"{label}_{prefix}", value)
    if candidate.publication_paper_item_id is not None:
        item = PaperItem.objects.filter(id=candidate.publication_paper_item_id).first()
        if item is not None and item.answer_key_version_id:
            reg(f"ANSWER_KEY_{prefix}", item.answer_key_version_id)



def main() -> int:
    setup_test_environment()
    old_name = connection.creation.create_test_db(verbosity=0, autoclobber=True)
    try:
        if MEDIA_ROOT.exists():
            shutil.rmtree(MEDIA_ROOT)
        MEDIA_ROOT.mkdir(parents=True, exist_ok=True)
        settings.PRIVATE_MEDIA_ROOT = str(MEDIA_ROOT)
        settings.MEDIA_ROOT = str(MEDIA_ROOT)
        reset_storage_cache()
        payload = build()
    finally:
        connection.creation.destroy_test_db(old_name, verbosity=0)
    for entry in SCENARIO_TITLES:
        entry["cases"] = [case["case"] for case in CASES if case["scenario"] == entry["scenario"]]
    payload["scenarios"] = SCENARIO_TITLES
    payload = remap(payload)
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(payload, ensure_ascii=False, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    digest = hashlib.sha256(OUT_JSON.read_bytes()).hexdigest()
    print(f"wrote {OUT_JSON} ({len(payload['cases'])} cases)")
    for case in payload["cases"]:
        print(f"  {case['case']:>4} {case['scenario']} {case['status']}  {case['title']}")
    print(f"sha256 {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

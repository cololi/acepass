def question_lines(number: int, prefix: str, *, stem: str = "下列说法正确的是？", options: int = 2) -> list[str]:
    """One short single-choice question: number line, stem, option block."""
    lines = [f"{number}．【题型】单选题", f"【题干】{prefix}第{number}题：{stem}", "【选项】"]
    letters = "ABCD"
    lines.extend(f"{letters[index]}. {'甲乙丙丁'[index]}" for index in range(options))
    return lines


def two_column_page(left_lines: list[str], right_lines: list[str], *, step: float = LINE_STEP) -> list[dict]:
    """Interleave the columns in content-stream order (row-major, i.e. the wrong reading order)."""
    fragments: list[dict] = []
    for index in range(max(len(left_lines), len(right_lines))):
        y = TOP_Y - index * step
        if index < len(left_lines):
            fragments.append({"x": LEFT_X, "y": y, "text": left_lines[index]})
        if index < len(right_lines):
            fragments.append({"x": RIGHT_X, "y": y, "text": right_lines[index]})
    return fragments


def encrypt_pdf(content: bytes, user_password: str) -> bytes:
    """RC4-128 with a fixed owner password: pypdf derives the file key from the document id."""
    writer = PdfWriter(clone_from=io.BytesIO(content))
    writer.encrypt(user_password=user_password, owner_password="acepass-b4-owner", algorithm="RC4-128")
    buffer = io.BytesIO()
    writer.write(buffer)
    return buffer.getvalue()


def zero_page_pdf() -> bytes:
    """A structurally valid PDF with zero pages: ``PdfWriter()`` writes no /Page at all."""
    writer = PdfWriter()
    buffer = io.BytesIO()
    writer.write(buffer)
    return buffer.getvalue()



def page_facts(document: SourceDocument, job: ImportJob | None = None) -> dict:
    """Every page of one fixture: the stored text plus the job's diagnosis row for that page."""
    rows = [
        row
        for row in ((job.page_diagnostics if job is not None else []) or [])
        if str(row.get("document_id")) == str(document.id)
    ]
    by_page: dict[int, dict] = {}
    for row in rows:
        by_page.setdefault(int(row.get("page_index") or 0), row)
    facts = []
    for index, text in enumerate(document.page_texts or [], start=1):
        row = by_page.get(index, {})
        facts.append(
            {
                "page_index": index,
                "text": text,
                "character_count": row.get("character_count"),
                "fragment_count": row.get("fragment_count"),
                "columns": row.get("columns"),
                "has_table_grid": row.get("has_table_grid"),
                "has_formula_tokens": row.get("has_formula_tokens"),
                "is_scanned": row.get("is_scanned"),
                "reading_order_reliable": row.get("reading_order_reliable"),
                "reasons": row.get("reasons"),
                "needs_review": row.get("needs_review"),
            }
        )
    return {"document": sym(document.id), "title": document.title, "page_count": document.page_count, "pages": facts}



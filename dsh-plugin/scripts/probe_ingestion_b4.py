def job_from_response(case_id: str) -> ImportJob | None:
    payload = RAW_PAYLOADS.get(case_id)
    if not isinstance(payload, dict):
        return None
    job_id = payload.get("id")
    if not job_id:
        return None
    return ImportJob.objects.filter(id=job_id).first()


def candidate_from_response(case_id: str) -> ImportCandidate | None:
    payload = RAW_PAYLOADS.get(case_id)
    if not isinstance(payload, dict):
        return None
    candidate_id = payload.get("id")
    if not candidate_id:
        return None
    return ImportCandidate.objects.filter(id=candidate_id).first()


